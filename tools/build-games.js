/** 8x8 pixel rows of 0-3 -> 16 CHR bytes (plane 0 then plane 1) */
function encodeTile(rows) {
  const out = new Uint8Array(16);
  for (let y = 0; y < 8; y++) {
    let p0 = 0, p1 = 0;
    for (let x = 0; x < 8; x++) {
      const c = rows[y][x];
      p0 |= (c & 1) << (7 - x);
      p1 |= ((c >> 1) & 1) << (7 - x);
    }
    out[y] = p0;
    out[y + 8] = p1;
  }
  return out;
}

export function buildChr() {
  const chr = new Uint8Array(8192);
  const put = (index, rows) => chr.set(encodeTile(rows), index * 16);
  META_ORDER.forEach((name, m) => {
    const px = METATILES[name].map((r) => [...r].map((c) => (c === '.' ? 0 : +c)));
    if (px.length !== 16 || px.some((r) => r.length !== 16)) throw new Error(`metatile ${name} must be 16x16`);
    for (let q = 0; q < 4; q++) {
      const oy = (q >> 1) * 8, ox = (q & 1) * 8;
      put(m * 4 + q, px.slice(oy, oy + 8).map((r) => r.slice(ox, ox + 8)));
    }
  });
  for (const [ch, glyph] of Object.entries(FONT)) {
    const rows = Array.from({ length: 8 }, (_, y) =>
      Array.from({ length: 8 }, (_, x) => (y < 7 && x >= 1 && x <= 5 && glyph[y][x - 1] === '#' ? 3 : 0)));
    put(ch.charCodeAt(0), rows);
  }
  return chr;
}

// ------------------------------------------------------------------ ROM
export function buildViper() {
  const source = readFileSync(join(root, 'games/pixel-viper/viper.asm'), 'utf8');
  const { bytes, symbols } = assemble(source);
  const prg = new Uint8Array(16384).fill(0xff);
  for (const [addr, b] of bytes) {
    if (addr < 0xc000) throw new Error(`code outside PRG at $${addr.toString(16)}`);
    prg[addr - 0xc000] = b;
  }
  const header = new Uint8Array([0x4e, 0x45, 0x53, 0x1a, 1, 1, 0x00, 0x00, 0, 0, 0, 0, 0, 0, 0, 0]);
  const rom = new Uint8Array(16 + 16384 + 8192);
  rom.set(header, 0);
  rom.set(prg, 16);
  rom.set(buildChr(), 16 + 16384);
  return { rom, symbols };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const check = process.argv.includes('--check');
  const out = join(root, 'roms/pixel-viper.nes');
  const { rom } = buildViper();
  if (check) {
    const same = existsSync(out) && Buffer.compare(readFileSync(out), Buffer.from(rom)) === 0;
    if (!same) { console.error('roms/pixel-viper.nes is out of date: run node tools/build-games.js'); process.exit(1); }
    console.log('roms/pixel-viper.nes is up to date');
  } else {
    mkdirSync(dirname(out), { recursive: true });
    writeFileSync(out, rom);
    console.log(`wrote roms/pixel-viper.nes (${rom.length} bytes)`);
  }
}
